"""Lightweight profiling of the three RAW CSVs (pandas is fine here: ~27 MB total).

    python scripts/profile_sources.py            # writes docs/data_profile.md

Every number in docs/data_profile.md comes from this script - nothing is typed by hand.
NB: country_codes.csv has a genuinely blank alpha-2 for Namibia, so pandas' default NA handling
and keep_default_na=False give the same result; we still disable default NA parsing so the
profile reflects the file, not pandas' interpretation.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from utils.config import (CHART_MAX_RANK, NON_COUNTRY_REGIONS, REGION_ALIASES, SPOTIFY_TRACK_URL_REGEX,  # noqa: E402
                          SOURCE_DATASETS, PROJECT_ROOT)

RAW = ROOT / "data" / "raw"
rd = lambda n: pd.read_csv(RAW / SOURCE_DATASETS[n]["file"], keep_default_na=False, na_values=[""])
out: list[str] = []
p = out.append


def table(df: pd.DataFrame) -> None:
    p("| " + " | ".join(map(str, df.columns)) + " |")
    p("|" + "---|" * len(df.columns))
    for _, r in df.iterrows():
        p("| " + " | ".join(str(v) for v in r.values) + " |")
    p("")


def schema_table(df: pd.DataFrame) -> None:
    t = pd.DataFrame({"column": df.columns, "pandas dtype": [str(x) for x in df.dtypes],
                      "nulls": df.isna().sum().values, "distinct": [df[c].nunique() for c in df.columns]})
    table(t)


tracks, charts, countries = rd("tracks"), rd("charts"), rd("countries")
p("# Source data profile (generated by `scripts/profile_sources.py`)\n")
p("Numbers below were computed from the files in `data/raw/`; they drove the design decisions in "
  "`docs/transformations.md`.\n")

# ------------------------------------------------------------------ tracks
p(f"## tracks.csv - {len(tracks):,} rows x {tracks.shape[1]} columns\n")
schema_table(tracks)
idx = tracks.iloc[:, 0]
p(f"- First column has an **empty header** and holds {idx.min()}..{idx.max()}; unique and contiguous = "
  f"{bool((idx == range(len(tracks))).all())} -> artificial pandas index.")
p(f"- Fully identical rows: {int(tracks.duplicated().sum())}. Distinct `track_id`: {tracks.track_id.nunique():,} "
  f"-> **{int(tracks.track_id.duplicated().sum()):,} repeated rows** (same track listed once per genre).")
g = tracks.groupby("track_id")
nun = g[["popularity", "duration_ms", "danceability", "energy", "tempo", "track_name", "artists", "album_name", "explicit"]].nunique()
multi = g.size() > 1
p(f"- Track ids with >1 row: {int(multi.sum()):,} (max {int(g.size().max())} rows). Within those groups the number of ids "
  f"whose value differs: " + ", ".join(f"{c}={int((nun[multi][c] > 1).sum())}" for c in nun.columns) + ".")
p(f"- Distinct genres: {tracks.track_genre.nunique()}.")
bad = {"rows with null track_name/artists/album_name": int(tracks[["artists", "album_name", "track_name"]].isna().any(axis=1).sum()),
       "duration_ms <= 0": int((tracks.duration_ms <= 0).sum()), "tempo == 0": int((tracks.tempo == 0).sum()),
       "time_signature == 0": int((tracks.time_signature == 0).sum()), "popularity outside 0..100": int((~tracks.popularity.between(0, 100)).sum()),
       "audio features outside [0,1]": int(sum((~tracks[c].between(0, 1)).sum() for c in
                                              ["danceability", "energy", "speechiness", "acousticness", "instrumentalness", "liveness", "valence"])),
       "loudness > 0 dB": int((tracks.loudness > 0).sum()), "duration > 1 hour": int((tracks.duration_ms > 3_600_000).sum()),
       "popularity == 0": int((tracks.popularity == 0).sum())}
p("\n**Invalid / suspicious values**\n")
table(pd.DataFrame({"check": list(bad), "rows": list(bad.values())}))
p("**Numeric summary**\n")
table(tracks.describe().T.round(3).reset_index().rename(columns={"index": "column"}))

# ------------------------------------------------------------------ charts
p(f"## charts_sample.csv - {len(charts):,} rows x {charts.shape[1]} columns\n")
schema_table(charts)
ids = charts.url.astype(str).str.extract(SPOTIFY_TRACK_URL_REGEX)[0]
charts = charts.assign(track_id=ids)
dates = sorted(charts.date.unique())
p(f"- Date range {charts.date.min()} .. {charts.date.max()}, but only **{len(dates)} distinct dates** (a sample, not a continuous history): "
  + ", ".join(dates) + ".")
p(f"- Chart types: {charts.chart.value_counts().to_dict()}; trend values: {charts.trend.value_counts().to_dict()}.")
p(f"- Rank range {charts['rank'].min()}..{charts['rank'].max()}; viral50 max rank {charts[charts.chart == 'viral50']['rank'].max()}; "
  f"streams {int(charts.streams.min()):,}..{int(charts.streams.max()):,}; null streams {int(charts.streams.isna().sum())} "
  f"(all in: {charts[charts.streams.isna()].chart.value_counts().to_dict()}).")
p(f"- Spotify track id extracted from `url`: {int(ids.notna().sum()):,}/{len(charts):,}; distinct track ids {ids.nunique():,}.")
p(f"- Duplicates: full row {int(charts.duplicated().sum())}; (date, region, chart, rank) {int(charts.duplicated(['date', 'region', 'chart', 'rank']).sum())}; "
  f"(date, region, chart, track_id) {int(charts.duplicated(['date', 'region', 'chart', 'track_id']).sum())}.")
in_t = charts.track_id.isin(tracks.track_id)
p(f"- **Join to tracks.csv on track_id: {int(in_t.sum()):,}/{len(charts):,} chart rows ({100 * in_t.mean():.2f}%) match; "
  f"{charts[in_t].track_id.nunique()} of {charts.track_id.nunique():,} distinct chart tracks.**")
p(f"- Distinct regions: {charts.region.nunique()}; rows with region 'Global': {int((charts.region == 'Global').sum()):,}.\n")

# ------------------------------------------------------------------ countries
p(f"## country_codes.csv - {len(countries)} rows x {countries.shape[1]} columns\n")
schema_table(countries)
p(f"- Duplicate rows {int(countries.duplicated().sum())}; distinct alpha-3 {countries['alpha-3'].nunique()}; distinct names {countries.name.nunique()}.")
p(f"- Blank `alpha-2`: {countries[countries['alpha-2'].isna()].name.tolist()} (the value is blank **in the file**; `iso_3166-2` still holds it: "
  f"{countries[countries['alpha-2'].isna()]['iso_3166-2'].tolist()}).")
p(f"- Rows with blank `region`: {countries[countries.region.isna()].name.tolist()}.")
reg = set(charts.region.unique())
exact = reg & set(countries.name)
alias_ok = {k: v for k, v in REGION_ALIASES.items() if v in set(countries.name)}
left = reg - exact - set(alias_ok) - set(NON_COUNTRY_REGIONS)
p(f"- Chart regions matching a country name exactly: {len(exact)}/{len(reg)}. Not matching: {sorted(reg - exact)}.")
p(f"- With the configured aliases ({len(alias_ok)}) and 'Global' treated as a non-country, unresolved regions: {sorted(left)}.")
(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "data_profile.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/data_profile.md")
